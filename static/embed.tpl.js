function pickLang() {
  var fixed = '__LANG__';
  if (fixed && I18N[fixed]) return fixed;      // 后台给该网站指定了语言
  var ls = [];
  try { if (navigator.languages && navigator.languages.length) ls = navigator.languages.slice(); } catch (e) {}
  if (!ls.length) ls = [navigator.language || navigator.userLanguage || 'zh'];
  for (var i = 0; i < ls.length; i++) {
    var c = String(ls[i]).toLowerCase().split('-')[0];
    if (I18N[c]) return c;
  }
  return 'zh';
}
var LANG = pickLang();
var L = I18N[LANG] || I18N.zh;
function tr(key) { return (L && L[key]) || I18N.zh[key]; }

/* 服务端中文提示 -> 语言键（服务端只回规范语义 key，前端负责翻译） */
function msgKey(m) {
  if (!m) return 'invalid';
  if (m.indexOf('频繁') >= 0) return 'rate';
  if (m.indexOf('过期') >= 0 || m.indexOf('已使用') >= 0) return 'expired';
  if (m.indexOf('未激活') >= 0) return 'notyet';
  if (m.indexOf('仅限') >= 0) return 'limit';
  if (m.indexOf('无效') >= 0 || m.indexOf('不存在') >= 0) return 'invalid';
  return '';
}

/* 把服务端提示翻译成当前语言；占位符 {d} 用服务端原域名替换 */
function msgText(key, raw) {
  if (!key || !I18N.zh[key]) return raw || tr('invalid');
  var out = tr(key);
  var m = /仅限\s*(\S+)\s*使用/.exec(raw || '');
  if (m) out = out.replace('{d}', m[1]);
  return out;
}

